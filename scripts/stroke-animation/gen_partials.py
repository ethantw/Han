#!/usr/bin/env python3
"""strokes.json → 首頁生成物（單一來源）。

生成 home/_shared.html 的共用 i18n `logo`／`han` token：漢.css wordmark，
「漢」是尚古傳承字形 SVG 輪廓（筆順序、nonzero 填實）。全站唯一的漢
輪廓來源——brand 兩處由 build 以 {{ logo }} 代入，Manifesto 水印由
fonts-gate.js 執行時 clone 本 SVG 的 path 建構。整檔生成。

（活字盤鉛字改用 woff2 網頁字直接排版，不再生成輪廓。）
"""
import json
from pathlib import Path

from stroke_order import ORDER

HERE = Path(__file__).parent
HAN = Path('/Users/yijun/Workspace/hanzi.pro/han')
SHARED = HAN / 'manual/home/_shared.html'

data = json.loads((HERE / 'strokes.json').read_text())
chars = {e['char']: e for e in data['chars']}
for e in chars.values():
    e['strokes'] = [e['strokes'][k] for k in ORDER[e['char']]]

VIEWBOX = data['viewBox']
GEN_NOTE = 'generated by scripts/stroke-animation/gen_partials.py — do not hand-edit'


# ─── 共用 logo token（漢.css wordmark，「漢」nonzero 填實輪廓） ───
# wordmark 原子（mark＋dot＋ext）——brand 兩處各自以自己的 .Brand 外殼
# 包 {{ logo }}（header 是 <a>＋副標、hero 是 <span>）。SVG 的 path 依
# 筆順序排列（水印逐筆描邊靠此序），填實時 order 無影響。
#
# 不寫 fill-rule，也就是用 SVG 預設的 nonzero——字體輪廓本來就是照 nonzero
# 設計的（外框與內白反向繞行）。這裡曾經寫 evenodd，而思源系的字形**保留
# 筆畫交疊**（那是 VF 插值的規格級約束，見工作區 CLAUDE.md），交疊區在
# evenodd 下互相抵消就成了白洞：十二條 path 裡有兩條帶兩個子路徑
# （豎筆＋橫槓），各被挖掉一塊。改回 nonzero 之後交疊填實，而廿、日 之類
# 的內白是筆畫之間的間隙、不靠填充規則，所以一個都沒少。
# G3 字徽（favicon 同款；三圓＋1B 明體頓點）——logo token 的第一個原子，
# 與 docs Masthead 同源。此前只手寫進「生成物」_shared.html（eb7778e、
# 1bd41de 兩次），生成器一跑就會抹掉它；搬回這裡才真的 single-source。
LOGO_SVG = '<svg class="BrandMark" viewBox="0 0 100 100" aria-hidden="true"><circle cx="20" cy="28" r="6.5" opacity=".55" /><circle cx="20" cy="50" r="9.5" /><circle cx="20" cy="78" r="12.5" opacity=".85" /><path class="brace" d="M 82 14 H 57 V 86 H 82" fill="none" stroke-width="6.5" stroke-linecap="square" stroke-linejoin="miter" /><polygon class="dun" points="58,45 43,50 58,55" /></svg>'

brand_paths = ''.join(f'<path d="{s["d"]}" />' for s in chars['漢']['strokes'])
brand_glyph = (
    f'<svg class="BrandGlyph" viewBox="{VIEWBOX}" aria-hidden="true">'
    f'{brand_paths}</svg>'
)
# 放大鏡的用法提示。兩種指針共用一句：滑鼠與觸控的動作不同（移動 vs 拖動），
# 但「雙擊開關」是同一件事，而拖動在觸控上本來就是移動的意思。
#
# 它跟字形無關，住在這裡的理由只有一個：_shared.html 是整檔生成的，手寫進
# 生成物的東西下一次跑生成器就沒了（G3 字徽已經被抹掉過兩次）。凡是要放進
# 這一份的 token，源頭都得在這支腳本裡。
LENS_HINT = {
    'hant': '雙擊樣張開關放大鏡，拖動可移動。',
    'hans': '双击样张开关放大镜，拖动可移动。',
    'en': 'Double-click the specimen to toggle the loupe; drag to move it.',
    'ja': '見本をダブルクリックで拡大鏡を切り替え、ドラッグで動かせる。',
    'ko': '<ruby>見本<rt>견본</rt></ruby>을 두 번 누르면 <ruby>擴大鏡<rt>확대경</rt></ruby>이 켜진다。끌어서 옮길 수 있다。',
}
lens_hint = '\n'.join(f"    {k}: '{v}'," for k, v in LENS_HINT.items())

shared = f'''<script type="text/x-i18n">
// 全站共用、跨語言不變的 token（build 併進每個模版 ctx）。
// 尚古傳承字形「漢」SVG 輪廓——寫一次（HAN_SVG），兩個 token 引用它，
// 產物與源頭皆 single-source（本檔由 strokes.json 生成）。
//   logo：漢.css wordmark 原子（.Brand 殼＋G3 字徽＋mark 內含該 SVG＋
//         dot＋ext）。
//   han ：裸 SVG 本體，直接複用、不必從 logo 的 wrapper 裡取。
// Manifesto 水印另由 fonts-gate.js 執行時 clone 該 SVG 的 path。
// ⚠️ {GEN_NOTE}
const HAN_SVG = `{brand_glyph}`
return {{
  // 放大鏡的用法提示。兩種指針共用一句：滑鼠與觸控的動作不同（移動 vs 拖動），
  // 但「雙擊開關」是同一件事，而拖動在觸控上本來就是移動的意思。
  lensHint: {{
{lens_hint}
  }},
  logo: {{
    "*": `<span class="Brand">{LOGO_SVG}<span data-part="mark">${{HAN_SVG}}漢</span><span data-part="dot">.</span><span data-part="ext">css</span></span>`,
  }},
  han: {{
    "*": HAN_SVG,
  }},
}}
</script>
'''

# _shared.html 整檔生成
SHARED.write_text(shared)
print(f'✓ {SHARED.name} 已生成（logo token）')
