#!/usr/bin/env python3
"""strokes.json → 首頁模板內聯 SVG（乙・Manifesto 水印＋甲・TypeTray 鉛字盤）。

以標記註解圈住生成區塊，重跑冪等：
  <!-- stroke-anim:watermark:begin --> … <!-- stroke-anim:watermark:end -->
  <!-- stroke-anim:slugs:begin -->     … <!-- stroke-anim:slugs:end -->
首次執行時自動把原始的 .Outline span／.Slugs <p> 換成標記區塊。
"""
import json
import re
from pathlib import Path

from stroke_order import ORDER

HERE = Path(__file__).parent
HAN = Path('/Users/yijun/Workspace/hanzi.pro/han')
MANIFESTO = HAN / 'manual/home/manifesto.html'
STATION_TYPE = HAN / 'manual/home/station-type.html'

data = json.loads((HERE / 'strokes.json').read_text())
chars = {e['char']: e for e in data['chars']}
for e in chars.values():
    e['strokes'] = [e['strokes'][k] for k in ORDER[e['char']]]

VIEWBOX = data['viewBox']
GEN_NOTE = 'generated by scripts/stroke-animation/gen_partials.py — do not hand-edit'


def paths_of(ch, indent):
    return '\n'.join(
        f'{indent}<path class="Stroke" style="--i: {i}" pathLength="1" d="{s["d"]}" />'
        for i, s in enumerate(chars[ch]['strokes'])
    )


# ─── 乙・Manifesto 水印（漢，輪廓逐筆） ───
watermark = f'''<!-- stroke-anim:watermark:begin ({GEN_NOTE}) -->
  <span class="Outline" aria-hidden="true">
    <svg viewBox="{VIEWBOX}">
{paths_of('漢', '      ')}
    </svg>
  </span>
  <!-- stroke-anim:watermark:end -->'''

# ─── 甲・TypeTray 鉛字盤（六顆，鏡像雕刻） ───
slug_spans = []
for ci, ch in enumerate('漢字標準格式'):
    accent = ' data-accent' if ch == '標' else ''
    slug_spans.append(f'''      <span{accent} style="--c: {ci}">
        <svg viewBox="{VIEWBOX}">
{paths_of(ch, '          ')}
        </svg>
      </span>''')
slugs = f'''<!-- stroke-anim:slugs:begin ({GEN_NOTE}) -->
    <p class="Slugs" aria-hidden="true">
{chr(10).join(slug_spans)}
    </p>
    <!-- stroke-anim:slugs:end -->'''


def patch(path, begin, end, block, first_run_re):
    src = path.read_text()
    marked = re.compile(re.escape(begin) + r'.*?' + re.escape(end), re.S)
    if begin in src:
        out, n = marked.subn(block, src)
    else:
        out, n = first_run_re.subn(block, src, count=1)
    if n != 1:
        raise SystemExit(f'✗ {path.name}: 找不到插入點')
    path.write_text(out)
    print(f'✓ {path.name} 已更新')


patch(
    MANIFESTO,
    '<!-- stroke-anim:watermark:begin', ':watermark:end -->',
    watermark,
    re.compile(r'<span class="Outline" aria-hidden="true">漢</span>'),
)
patch(
    STATION_TYPE,
    '<!-- stroke-anim:slugs:begin', ':slugs:end -->',
    slugs,
    re.compile(r'<p class="Slugs" aria-hidden="true">.*?</p>', re.S),
)
